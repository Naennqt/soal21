const prompt=require('prompt-sync')({sigint:true})
let nilai = Number(prompt('Masukkan Nilai  : '))
if (nilai >= 90 && nilai < 100)
    console.log(`GRADE A`)
else if (nilai >= 80 && nilai <90)
    console.log(`GRADE B`)
else if(nilai >=70 && nilai<80)
    console.log(`GRADE C`)
else if (nilai >=60 && nilai<70 )
    console.log(`GRADE D`)
else
    console.log(`GRADE E`)